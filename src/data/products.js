export function getProduct(id) {
  return products.find((product) => product.id === id) || null;
}

export function relatedProducts(product, count = 4) {
  return products
    .filter((item) => item.category === product.category && item.id !== product.id && item.stock > 0)
    .slice(0, count);
}

export function featuredWeight(product) {
  return product.weights.find((weight) => weight.size === "5 kg") || product.weights[0];
}

export function weightBySize(product, size) {
  return product.weights.find((weight) => weight.size === size) || featuredWeight(product);
}

export const varieties = [...new Set(products.map((product) => product.variety))].sort();
export const origins = [...new Set(products.map((product) => product.origin))].sort();
